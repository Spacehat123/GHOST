#!/usr/bin/env python3
"""T1a store census — the mechanical truth, regenerable (ROADMAP_TOTAL_AUTONOMY §T1a).

Dumps: every SQLite store (existing on disk OR declared in code), every
state/knob JSON file, every env-overridable store path, with schemas, declared
FKs, row counts. Read-only on live DBs (mode=ro). Output: markdown to stdout
(docs/store_census.generated.md is the committed snapshot).

Judgment lives in docs/MIGRATION_MAP.md — this script only reports facts.
Run: python3 scripts/store_census.py [repo_root]
"""
